    public static String category(String cat) {
        String s = CATS.get(cat);
        return s != null ? s : cat;
    }

    /** {название, описание} или null, если пункта нет в словаре. */
    public static String[] row(String cat, String key) {
        if ("prices".equals(cat)) {
            for (AbilityType t : AbilityType.values()) {
                String pref = t.id + "Level";
                if (key.startsWith(pref)) {
                    String n = Lang.RU.get(t.titleKey());
                    return new String[] { "Цена: " + (n != null ? n : t.id) + ", ур. " + key.substring(pref.length()),
                            "Цена этого уровня в магазине. Если стоит 0, используется цена по умолчанию." };
                }
            }
            return null;
        }
        return ROWS.get(cat + "|" + key);
    }

    /** Порядок категорий задаёт номер в ключах перевода (ключи в .lang только латиницей). */
    private static final String[] CAT_IDS = { "мана", "управление", "кредит", "карман", "способности", "тотемы",
            "невидимость", "спектор", "тепловизор", "щит", "полёт", "тело", "удача", "мягкое_падение", "магнит",
            "замедление", "интерфейс", "волна", "prices", "сканер", "склад", "рывок", "изгнанник" };

    private static int idx(String cat) {
        for (int i = 0; i < CAT_IDS.length; i++) if (CAT_IDS[i].equals(cat)) return i;
        return -1;
    }

    /** Ключ перевода для названия пункта (или null, если категория неизвестна). */
    public static String langKey(String cat, String key) {
        int i = idx(cat);
        return i < 0 ? null : "pocketmod.cfg." + i + "." + key;
    }

    public static String catLangKey(String cat) {
        int i = idx(cat);
        return i < 0 ? null : "pocketmod.cfg.cat." + i;
    }
